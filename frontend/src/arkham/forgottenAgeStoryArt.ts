export function forgottenAgeStoryArtFor(
  campaignId: string | undefined,
  entries: FlavorTextEntry[],
): string | undefined {
  if (!campaignId || !campaignIds.has(campaignId)) return

  for (const key of entryKeys(entries, { includeInvalid: false })) {
    if (!key.startsWith(campaignPrefix)) continue
    // The combined scenario and the two split scenarios have identical story passages.
    const passage = key.slice(campaignPrefix.length)
      .replace(/^heartOfTheEldersPart[12](?=\.)/, 'heartOfTheElders')
    if (Object.hasOwn(forgottenAgeStoryArtByPassage, passage)) return forgottenAgeStoryArtByPassage[passage]
  }
}
